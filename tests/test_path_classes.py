def test_every_finding_carries_its_context_in_findings_json_and_sarif(scanned):
    results = scanned / ".security-scan"
    findings = json.loads((results / "findings.json").read_text())["findings"]
    by_path = {f["path"]: f["context"] for f in findings}
    assert by_path == {"config.py": "source", "tests/test_config.py": "test"}

    sarif = json.loads((results / "results.sarif").read_text())
    contexts = {r["locations"][0]["physicalLocation"]["artifactLocation"]["uri"]:
                r["properties"]["context"] for r in sarif["runs"][0]["results"]}
    assert contexts == by_path


def test_a_findings_identity_does_not_depend_on_its_class(scanned, monkeypatch):
    from valvur import api
    from valvur.adapters import GitleaksAdapter

    def fingerprints() -> dict[str, str]:
        doc = json.loads((scanned / ".security-scan" / "findings.json").read_text())
        return {f["path"]: f["fingerprint"] for f in doc["findings"]}

    before = fingerprints()
    monkeypatch.setattr(pathclass, "of", lambda path: "vendored")
    api.scan(scanned, runner=LocalRuntime(FAKE_TOOLS), adapters=[GitleaksAdapter()])

    assert fingerprints() == before
