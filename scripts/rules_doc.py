"""`docs/RULES.md`: every shipped rule's precision, measured (R29.3, D65b).

    uv run python scripts/rules_doc.py            # write docs/RULES.md
    uv run python scripts/rules_doc.py --check    # exit 1 when it is not current

Rendered from `tests/eval/rules-measured.json`, which `scripts/eval.py --rules-measured`
writes from the Score's scans of tracks 1 and 2 and the corpus. The bar and each
rule's state are `scripts/eval/rule_precision.py`'s, so the page and the test that
keeps active rules over the bar read one definition.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts" / "eval"))

import rule_precision  # type: ignore[import-not-found]  # noqa: E402

MEASURED = REPO / "tests" / "eval" / "rules-measured.json"
PAGE = REPO / "docs" / "RULES.md"


#: A place a measurement predates: track 9 before R41.
_NONE = {"tp": 0, "fp": 0, "unjudged": 0}


def _cell(counts: dict) -> str:
    cell = f"{counts['tp']} / {counts['fp']}"
    return f"{cell}, {counts['unjudged']} unjudged" if counts.get("unjudged") else cell


def _corpus(counts: dict) -> str:
    """A corpus cell: a rule with fewer than ADR-0033's judged Findings there says so."""
    judged = counts["tp"] + counts["fp"]
    parts = [f"{counts['tp']} / {counts['fp']}" if judged else "",
             "unmeasured there" if judged < rule_precision.MEASURED_FROM else "",
             f"{counts['unjudged']} unjudged" if counts.get("unjudged") else ""]
    return ", ".join(part for part in parts if part)


_SCANNERS = {"gitleaks": "Gitleaks", "checkov": "Checkov", "zizmor": "zizmor",
             "opengrep": "Opengrep"}


#: A rule that reports nothing by itself (R49.7): valvur reads its marks to write one
#: coverage note. `valvur.model_output.CALL_RULE` names it; a test holds the two together.
MARKS = {"valvur.llm.model-call":
         "a mark for the note on model output; reports nothing by itself"}

#: What the page says of a rule the tier table names (R49.3, R49.4, ADR-0033), by where
#: its row applies.
TIERED = "inventory: under the bar on maintained code"
TIERED_WHERE = {
    "everywhere": TIERED,
    "test material": "inventory under a test, fixture, documentation or example path: under "
                     "the bar on maintained code",
}


def tier_rows() -> dict[tuple[str, str], str]:
    """(Scanner, rule) to where its row applies, for each row of the tier table valvur
    ships."""
    from valvur import tiers  # deferred: the page's tests render canned tables without it

    return {(row.scanner, row.id): row.where for row in tiers.rows()}


def _others(measured: dict, listed: dict[tuple[str, str], str]) -> list[str]:
    """The second table (R48.4): every other rule that fired on the corpus."""
    rows = measured.get("others") or []
    if not rows:
        return []
    lines = [
        "", "## Every other rule that fired on the corpus", "",
        "Gitleaks', Checkov's and zizmor's rules and valvur's own Checks, each with two",
        "measurements that are never added together. *On maintained code* is the corpus:",
        "Gitleaks' and the Checks' Findings from `tests/eval/labels/corpus.toml`, Checkov's",
        "and zizmor's from `tests/eval/labels/hygiene.toml`, where a rule with more than 25",
        "Findings is judged on the 25 with the lowest Fingerprints and marked *sampled*.",
        "*On planted cases* is the Score's planted tracks: true on a vulnerable case, false",
        f"on a safe one. A rule with fewer than {rule_precision.MEASURED_FROM} judged Findings "
        "on the corpus is",
        "*unmeasured there* (ADR-0033).",
        "",
        "| rule | Scanner | on maintained code | on planted cases | note |",
        "|---|---|---|---|---|"]
    for row in rows:
        corpus = row["corpus"]
        notes = [f"sampled: {corpus['judged']} of {corpus['findings']} judged"
                 if corpus["sampled"] else "",
                 TIERED_WHERE.get(listed.get((row["scanner"], row["rule"]), ""), "")]
        note = "".join(f" {part}" for part in ["; ".join(n for n in notes if n)] if part)
        lines.append(f"| `{row['rule']}` | {_SCANNERS.get(row['scanner'], row['scanner'])} | "
                     f"{_corpus(corpus)} | {_cell(row['planted'])} |{note} |")
    return lines


def render(measured: dict, tiered: dict[tuple[str, str], str] | None = None) -> str:
    listed = tier_rows() if tiered is None else tiered
    lines = [
        "<!-- Generated by scripts/rules_doc.py from tests/eval/rules-measured.json; do not",
        "     edit by hand. -->",
        "",
        "# The rules valvur ships, and how precise each is",
        "",
        "Every static-analysis rule valvur runs through Opengrep, measured on what valvur",
        "reports over the Score's track 1 (the OWASP Benchmark for Python), track 2 (the",
        f"JavaScript twins), the corpus of {measured['corpus_projects']} real projects, whose "
        "every",
        "active finding is labelled by hand (`tests/eval/labels/corpus.toml`), and track 9:",
        "model output reaching a sink, in generated twins and in published advisories' code.",
        "A cell is true / false positives; a finding on a case of another weakness is not",
        "counted.",
        "",
        "**The bar** is ADR-0029's: at least one true positive and a precision of at least",
        "0.5, over four places summed: tracks 1, 2 and 9 and the corpus. For a rule vendored",
        "from GitLab's `sast-rules`, also one true",
        "positive at a line valvur's own rules do not already report. A rule under it is",
        "moved to the **inventory**, where its findings are reported for review and never",
        "count toward the verdict, with the reason below. The sink rules are inventory by",
        "design (D47a); an inventory finding on the corpus has no label, and is *unjudged*.",
        "",
        "A rule under ADR-0033's bar on maintained code, with five or more judged Findings",
        "there and fewer than half of them true, is inventory too, whichever Scanner's it",
        "is: its Findings are listed for review and never active. Those rules are the rows",
        "of `src/valvur/data/tiers.toml`, and read *" + TIERED + "* below.",
        "A rule that matches a shape, such as a private key's header, is listed only under a",
        "test, fixture, documentation or example path, and stays active everywhere else. A",
        "rule that matches a provider's own format has no row: a live-format key in a test",
        "is still a key.",
        "",
        "**Unmeasured** means no case of the rule's weakness in any of the four, so",
        "nothing here says how precise it is. Each fires on the cases planted for it in",
        "valvur's own tests and fixtures, and stays active. A corpus cell that reads",
        f"*unmeasured there* has fewer than {rule_precision.MEASURED_FROM} judged Findings on "
        "maintained code (ADR-0033).",
        "",
        "| rule | source | CWE | track 1 | track 2 | corpus | track 9 | precision | state |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for rule, row in sorted(measured["rules"].items()):
        places = row["places"]
        source = "GitLab sast-rules" if row["vendored"] else "valvur"
        cwe = ", ".join(f"CWE-{n}" for n in row["cwe"]) or "-"
        measured_at_all = row["tp"] + row["fp"]
        stands = MARKS.get(rule) or TIERED_WHERE.get(listed.get(("opengrep", rule), ""), "") \
            or rule_precision.state(row)
        lines.append(
            f"| `{rule}` | {source} | {cwe} | {_cell(places['sast-python'])} | "
            f"{_cell(places['sast-js'])} | {_corpus(places['corpus'])} | "
            f"{_cell(places.get('llm-output', _NONE))} | "
            f"{row['precision'] if measured_at_all else '-'} | {stands} |")
    lines += _others(measured, listed)
    lines += ["", f"Measured {measured['measured']} on `valvur:dev` (`{measured['image']}`).",
              ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when not current")
    args = parser.parse_args(argv)
    page = render(json.loads(MEASURED.read_text(encoding="utf-8")))
    if args.check:
        if not PAGE.is_file() or PAGE.read_text(encoding="utf-8") != page:
            print("docs/RULES.md is not current; run scripts/rules_doc.py", file=sys.stderr)
            return 1
        return 0
    PAGE.write_text(page, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
